# 吊装方法选择（按设备重量）
def select_lifting_method(weight_t: float, height_m: float = None, radius_m: float = None) -> dict:
    """根据设备重量/吊装高度/半径选择吊装方法和吊车型号。

    Returns:
        {method, crane_type, capacity, notes}
    """
    if weight_t <= 0:
        return {"method": "人工/手动", "crane_type": "手动葫芦/叉车", "capacity": "≤2t", "notes": "轻型设备，可使用手动葫芦或叉车"}

    if weight_t <= 2:
        return {"method": "手动吊装", "crane_type": "手动葫芦/叉车/液压叉车",
                "capacity": "≤2t", "notes": "轻型设备，可使用手动葫芦、叉车或液压叉车"}
    elif weight_t <= 5:
        return {"method": "汽车吊", "crane_type": "8t/12t汽车吊",
                "capacity": "≤5t", "notes": "小型设备，8t或12t汽车吊即可满足"}
    elif weight_t <= 10:
        return {"method": "汽车吊", "crane_type": "16t/20t汽车吊",
                "capacity": "≤10t", "notes": "中小型设备，16t或20t汽车吊"}
    elif weight_t <= 25:
        return {"method": "汽车吊", "crane_type": "25t汽车吊",
                "capacity": "≤25t", "notes": "中型设备，25t汽车吊（常用）"}
    elif weight_t <= 50:
        return {"method": "汽车吊", "crane_type": "50t汽车吊",
                "capacity": "≤50t", "notes": "中大型设备，50t汽车吊"}
    elif weight_t <= 100:
        return {"method": "汽车吊/履带吊", "crane_type": "100t汽车吊或100t履带吊",
                "capacity": "≤100t", "notes": "大型设备，100t汽车吊或履带吊；需编制专项吊装方案"}
    elif weight_t <= 200:
        return {"method": "履带吊", "crane_type": "150t/200t履带吊",
                "capacity": "≤200t", "notes": "重型设备，150t或200t履带吊；必须编制专项吊装方案并专家论证"}
    else:
        return {"method": "大型履带吊/塔吊/门式起重机", "crane_type": "300t以上履带吊或塔吊",
                "capacity": ">200t", "notes": "超重型设备，需300t以上履带吊或塔吊；必须专项方案+专家论证+安监备案"}


def identify_equipment_type(tag: str = "", name: str = "") -> str:
    """识别设备类型。

    Args:
        tag: 设备位号（如 P-101）
        name: 设备名称（如 离心泵）

    Returns:
        设备类型字符串
    """
    # 1) 从设备名称识别
    if name:
        name_lower = str(name).lower()
        for pattern, eq_type in NAME_KEYWORD_MAP:
            if re.search(pattern, name_lower, re.IGNORECASE):
                return eq_type

    # 2) 从位号前缀识别
    if tag:
        m = re.match(r"^([A-Z])-?\d", tag.upper())
        if m:
            prefix = m.group(1)
            if prefix in TAG_PREFIX_MAP:
                return TAG_PREFIX_MAP[prefix]

    return "其他"


def get_construction_steps(equipment_type: str) -> list:
    """获取设备类型对应的施工步骤。"""
    return CONSTRUCTION_STEPS.get(equipment_type, CONSTRUCTION_STEPS["其他"])


def get_equipment_type_from_devices(devices: list) -> str:
    """从设备列表中识别主要设备类型（取第一台）。"""
    if not devices:
        return "其他"
    first = devices[0]
    tag = first.get("tag", "") if isinstance(first, dict) else str(first)
    name = first.get("name", "") if isinstance(first, dict) else ""
    return identify_equipment_type(tag, name)


